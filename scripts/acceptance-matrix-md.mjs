// Renders docs/acceptance/feature-matrix.md from tests/acceptance/matrix/*.json and, when
// present, the gate results of one or more runs (test-results/acceptance/gate.json or paths
// given as arguments, e.g. one per browser). Usage:
//   node scripts/acceptance-matrix-md.mjs [gate.json ...] [--evidence "<versions and commands>"]
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'

const args = process.argv.slice(2)
const evidenceIndex = args.indexOf('--evidence')
const evidence = evidenceIndex >= 0 ? args[evidenceIndex + 1] : ''
const gateFiles = args.filter((arg, index) => arg.endsWith('.json') && index !== evidenceIndex + 1)
if (gateFiles.length === 0 && existsSync('test-results/acceptance/gate.json')) gateFiles.push('test-results/acceptance/gate.json')

const runs = gateFiles.map((file) => ({ file, gate: JSON.parse(readFileSync(file, 'utf8')) }))
const outcomes = new Map()
for (const { gate } of runs) {
  for (const row of gate.rows) {
    const list = outcomes.get(row.id) ?? []
    list.push(...row.results)
    outcomes.set(row.id, list)
  }
}

const escape = (text) => String(text ?? '').replaceAll('|', '\\|').replaceAll('\n', ' ')
const areas = readdirSync('tests/acceptance/matrix').filter((name) => name.endsWith('.json')).sort()
  .map((name) => JSON.parse(readFileSync(`tests/acceptance/matrix/${name}`, 'utf8')))

let total = 0
let passing = 0
const sections = areas.map((area) => {
  const lines = [`## ${area.description}`, '', '| ID | Feature | Scenarios | Negative | Fixture | Result | Issues |', '|---|---|---|---|---|---|---|']
  for (const row of area.rows) {
    total++
    const results = outcomes.get(row.id) ?? []
    const projects = [...new Set(results.map((result) => result.project))].sort()
    const ok = results.length > 0 && results.every((result) => result.outcome === 'passed')
    if (ok && row.required !== false) passing++
    const result = row.required === false ? `excluded (${escape(row.approval)})`
      : results.length === 0 ? 'not run'
        : ok ? `pass (${projects.join(', ')})`
          : `FAIL: ${results.filter((r) => r.outcome !== 'passed').map((r) => `${r.project} ${r.outcome}`).join(', ')}`
    const issues = (row.issues ?? []).map((issue) => {
      const match = String(issue).match(/^(?:([\w.-]+\/[\w.-]+))?#?(\d+)$/)
      if (!match) return escape(issue)
      const repo = match[1] ?? 'QRun-IO/qqq'
      return `[${repo === 'QRun-IO/qqq' ? '' : repo}#${match[2]}](https://github.com/${repo}/issues/${match[2]})`
    }).join(' ')
    lines.push(`| ${row.id} | ${escape(row.feature)} | ${escape((row.scenarios ?? []).join('; '))} | ${escape((row.negative ?? []).join('; '))} | ${escape(row.fixture)} | ${result} | ${issues} |`)
  }
  return lines.join('\n')
})

const header = [
  '# Next UI feature acceptance matrix',
  '',
  'Generated by `node scripts/acceptance-matrix-md.mjs` from `tests/acceptance/matrix/*.json` and the',
  'acceptance gate results. Each row is a supported QQQ UI feature or use case with executable',
  'real-backend acceptance coverage (QRun-IO/qqq#649). See `tests/acceptance/README.md` to run it.',
  '',
  `Rows: ${total}. Required rows passing in the recorded runs: ${passing}.`,
  '',
  runs.length ? `Recorded runs: ${runs.map(({ file, gate }) => `\`${file}\` (${gate.generatedAt}${gate.partial ? ', partial' : ''})`).join(', ')}.` : 'No recorded run.',
  ...(evidence ? ['', evidence] : []),
  '',
]
mkdirSync('docs/acceptance', { recursive: true })
writeFileSync('docs/acceptance/feature-matrix.md', header.join('\n') + '\n' + sections.join('\n\n') + '\n')
console.log(`Wrote docs/acceptance/feature-matrix.md (${total} rows, ${passing} passing required rows)`)
